export function randomCard(cards = CARDS) {
  return cards[Math.floor(Math.random() * cards.length)];
}

export function randomCardByLayer(layer) {
  const layerCards = CARDS.filter((card) => card.layer === layer);
  return randomCard(layerCards);
}
